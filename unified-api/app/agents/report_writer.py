def _content_to_flowables(text: str, styles: dict[str, ParagraphStyle]) -> list:
    flowables: list = []
    current_para: list[str] = []

    def flush():
        if current_para:
            joined = " ".join(current_para)
            flowables.append(Paragraph(_md_inline(joined), styles["body"]))
            current_para.clear()

    for line in text.split("\n"):
        stripped = line.strip()
        if not stripped:
            flush()
            continue

        if stripped.startswith("### "):
            flush()
            flowables.append(Paragraph(_md_inline(stripped[4:]), styles["h3"]))
            continue
        if stripped.startswith("## "):
            flush()
            flowables.append(Paragraph(_md_inline(stripped[3:]), styles["h2"]))
            continue

        bullet_m = re.match(r"^[\*\-]\s+", stripped)
        if bullet_m:
            flush()
            item_text = stripped[bullet_m.end() :]
            flowables.append(Paragraph(f"\u2022\u2003{_md_inline(item_text)}", styles["bullet"]))
            continue

        current_para.append(stripped)

    flush()
    return flowables


class ReportWriter:
    @staticmethod
    def build_pdf(
        portfolio_name: str,
        agent_outputs: list[AgentOutput],
        sections: list[str],
        report_type: str,
        run_date: date,
        section_agent_map: dict[str, str] | None = None,
    ) -> str:
        import time as _time

        t0 = _time.perf_counter()
        logger.info(
            "ReportWriter.build_pdf starting: portfolio=%s type=%s sections=%d agent_outputs=%d",
            portfolio_name,
            report_type,
            len(sections),
            len(agent_outputs),
        )
        os.makedirs(REPORTS_DIR, exist_ok=True)
        styles = _build_styles()

        filename = f"report_{run_date.isoformat()}_{uuid.uuid4().hex[:8]}.pdf"
        filepath = os.path.join(REPORTS_DIR, filename)

        frame = Frame(
            MARGIN_L,
            MARGIN_B,
            PAGE_W - MARGIN_L - MARGIN_R,
            PAGE_H - MARGIN_T - MARGIN_B,
            id="main",
        )
        template = PageTemplate(id="report", frames=[frame], onPage=_draw_footer)
        doc = BaseDocTemplate(
            filepath,
            pagesize=A4,
            pageTemplates=[template],
            title=f"PortfolioIQ \u2013 {report_type.title()} Report",
            author="PortfolioIQ AI System",
        )

        story: list = []

        story.append(Spacer(1, 1.5 * inch))
        story.append(Paragraph("PortfolioIQ Report", styles["title"]))
        story.append(Spacer(1, 8))
        type_label = report_type.replace("_", " ").title()
        story.append(
            Paragraph(
                f"{type_label} Report &mdash; {_esc(portfolio_name)}",
                styles["subtitle"],
            )
        )
        story.append(Paragraph(f"Generated: {run_date.isoformat()}", styles["subtitle"]))
        story.append(PageBreak())

        effective_map = {**DEFAULT_SECTION_AGENT_MAP, **(section_agent_map or {})}

        output_map: dict[str, AgentOutput] = {}
        for o in agent_outputs:
            output_map[o.agent_name] = o

        for section_name in sections:
            agent_name = effective_map.get(section_name)
            if not agent_name:
                continue
            output = output_map.get(agent_name)
            if not output:
                continue

            display = "Executive Summary" if section_name == "Exec Summary" else section_name
            story.append(Paragraph(display, styles["h1"]))

            summary = output.summary or ""
            if section_name == "Recommendations" and "Exec Summary" in sections:
                exec_end = summary.find("\n\n", 500)
                text = summary[exec_end:].strip()[:3000] if exec_end > 0 else summary[:3000]
            elif section_name == "Exec Summary":
                exec_end = summary.find("\n\n", 200)
                text = summary[:exec_end].strip() if exec_end > 0 else summary[:800]
            else:
                text = summary[:3000]

            story.extend(_content_to_flowables(text, styles))

            if output.predictions:
                preds = output.predictions if isinstance(output.predictions, list) else []
                if preds:
                    story.append(Spacer(1, 8))
                    story.append(Paragraph("Predictions", styles["h2"]))
                    story.append(Spacer(1, 4))

                    header = [
                        Paragraph("Prediction", styles["tbl_hdr"]),
                        Paragraph("Confidence", styles["tbl_hdr"]),
                        Paragraph("Timeframe", styles["tbl_hdr"]),
                    ]
                    data = [header]
                    for pred in preds[:5]:
                        data.append(
                            [
                                Paragraph(
                                    _esc(str(pred.get("prediction", ""))[:200]),
                                    styles["tbl_cell"],
                                ),
                                Paragraph(
                                    _esc(str(pred.get("confidence", ""))),
                                    styles["tbl_cell"],
                                ),
                                Paragraph(
                                    _esc(str(pred.get("timeframe", ""))),
                                    styles["tbl_cell"],
                                ),
                            ]
                        )

                    avail_w = PAGE_W - MARGIN_L - MARGIN_R
                    tbl = Table(
                        data,
                        colWidths=[avail_w * 0.62, avail_w * 0.16, avail_w * 0.22],
                        repeatRows=1,
                    )
                    tbl.setStyle(
                        TableStyle(
                            [
                                ("BACKGROUND", (0, 0), (-1, 0), _TBL_HDR),
                                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                                ("GRID", (0, 0), (-1, -1), 0.5, _GRAY_200),
                                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, _GRAY_50]),
                                ("TOPPADDING", (0, 0), (-1, -1), 5),
                                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                                ("LEFTPADDING", (0, 0), (-1, -1), 6),
                                ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                            ]
                        )
                    )
                    story.append(tbl)

            if output.judge_overall_score is not None:
                story.append(Spacer(1, 6))
                score = float(output.judge_overall_score)
                story.append(
                    Paragraph(
                        f"<b>Judge Accuracy Score:</b> {score:.1f}/10",
                        styles["body"],
                    )
                )

            story.append(Spacer(1, 12))

        story.append(Spacer(1, 16))
        story.append(Paragraph("Disclaimers", styles["h1"]))
        story.append(Paragraph(_esc(DISCLAIMER_TEXT), styles["disclaimer_body"]))

        doc.build(story)
        elapsed_ms = int((_time.perf_counter() - t0) * 1000)
        logger.info("ReportWriter.build_pdf complete: %s (elapsed=%dms)", filepath, elapsed_ms)
        return filepath
