"""Report Writer -- generates structured PDF reports from agent outputs."""

from __future__ import annotations

import logging
import os
import re
import uuid
from datetime import date

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER, TA_JUSTIFY
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.lib.utils import simpleSplit
from reportlab.platypus import (
    BaseDocTemplate,
    Frame,
    PageBreak,
    PageTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)

from app.models.agent import AgentOutput

logger = logging.getLogger(__name__)

REPORTS_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(__file__))), "reports")

DEFAULT_SECTION_AGENT_MAP = {
    "Exec Summary": "action_recommender",
    "Macro": "macro_analyst",
    "Risk": "risk_assessor",
    "Recommendations": "action_recommender",
}

DISCLAIMER_TEXT = (
    "DISCLAIMER: This report is generated by an AI system for informational "
    "purposes only. It does not constitute financial advice. Always consult a "
    "qualified financial advisor before making investment decisions. Past "
    "performance is not indicative of future results."
)

PAGE_W, PAGE_H = A4
MARGIN_L = 0.75 * inch
MARGIN_R = 0.75 * inch
MARGIN_T = 0.75 * inch
MARGIN_B = 1.0 * inch

_NAVY = colors.HexColor("#1a365d")
_BLUE = colors.HexColor("#2b6cb0")
_GRAY_50 = colors.HexColor("#f7fafc")
_GRAY_200 = colors.HexColor("#e2e8f0")
_GRAY_500 = colors.HexColor("#718096")
_GRAY_700 = colors.HexColor("#4a5568")
_TBL_HDR = colors.HexColor("#2d3748")


def _esc(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _md_inline(text: str) -> str:
    text = _esc(text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", text)
    text = re.sub(r"(?<!\*)\*(?!\*)(.+?)(?<!\*)\*(?!\*)", r"<i>\1</i>", text)
    return text


def _draw_footer(canvas, doc):
    """Render disclaimer + page number in the footer of every page."""
    canvas.saveState()

    y_line = MARGIN_B - 0.15 * inch
    canvas.setStrokeColor(_GRAY_200)
    canvas.setLineWidth(0.5)
    canvas.line(MARGIN_L, y_line, PAGE_W - MARGIN_R, y_line)

    canvas.setFont("Helvetica", 6.5)
    canvas.setFillColor(_GRAY_500)
    avail = PAGE_W - MARGIN_L - MARGIN_R
    lines = simpleSplit(DISCLAIMER_TEXT, "Helvetica", 6.5, avail)
    y_text = y_line - 10
    for ln in lines:
        canvas.drawString(MARGIN_L, y_text, ln)
        y_text -= 8

    canvas.setFont("Helvetica", 7)
    canvas.drawRightString(PAGE_W - MARGIN_R, 0.4 * inch, f"Page {doc.page}")

    canvas.restoreState()


