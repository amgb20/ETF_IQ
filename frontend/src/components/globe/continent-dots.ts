function polygonToCanvas(width: number, height: number): ImageData {
  const canvas = document.createElement("canvas");
  canvas.width = width;
  canvas.height = height;
  const ctx = canvas.getContext("2d")!;
  ctx.fillStyle = "#000";
  ctx.fillRect(0, 0, width, height);
  ctx.fillStyle = "#fff";

  for (const poly of CONTINENT_POLYS) {
    ctx.beginPath();
    for (let i = 0; i < poly.length; i++) {
      const [lat, lon] = poly[i];
      const x = ((lon + 180) / 360) * width;
      const y = ((90 - lat) / 180) * height;
      if (i === 0) ctx.moveTo(x, y);
      else ctx.lineTo(x, y);
    }
    ctx.closePath();
    ctx.fill();
  }

  return ctx.getImageData(0, 0, width, height);
}

export interface DotPoint {
  lat: number;
  lon: number;
  brightness: number;
}

export function generateContinentDots(count = 12000): DotPoint[] {
  const W = 720;
  const H = 360;
  const imageData = polygonToCanvas(W, H);
  const data = imageData.data;

  // Collect land pixels
  const landPixels: [number, number][] = [];
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      const idx = (y * W + x) * 4;
      if (data[idx] > 128) {
        landPixels.push([x, y]);
      }
    }
  }

  if (landPixels.length === 0) return [];

  // Sample `count` random land pixels
  const dots: DotPoint[] = [];
  for (let i = 0; i < count; i++) {
    const [px, py] = landPixels[Math.floor(Math.random() * landPixels.length)];
    const jx = px + (Math.random() - 0.5);
    const jy = py + (Math.random() - 0.5);
    const lon = (jx / W) * 360 - 180;
    const lat = 90 - (jy / H) * 180;
    dots.push({ lat, lon, brightness: 0.5 + Math.random() * 0.5 });
  }
  return dots;
}
